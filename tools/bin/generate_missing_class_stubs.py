#!/usr/bin/env python3
"""Emit Psalm stubs for classes a plugin references but does not define.

Psalm 6.x aborts with an uncaught InvalidArgumentException ("Could not get class storage
for <x>") when `instanceof`/`extends` narrows a value to a class it cannot resolve and a
method is then called on it. Suppressing UndefinedClass only silences the *report*; the
internal storage lookup still throws, so the whole run dies and the plugin gets zero taint
data. Gravity Forms hit this via `instanceof GFPayPal` -- a class that lives in a separate
paid add-on -- and produced 0 Psalm results as a result.

Declaring the missing classes as empty stubs lets analysis continue.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

REF_PATTERNS = [
    re.compile(r"\binstanceof\s+\\?([A-Z][A-Za-z0-9_\\]*)"),
    re.compile(r"\bextends\s+\\?([A-Z][A-Za-z0-9_\\]*)"),
]
DEF_PATTERN = re.compile(r"\b(?:class|interface|trait|enum)\s+([A-Za-z_][A-Za-z0-9_]*)")
# Anything the WordPress/PHP stubs already provide must not be redeclared.
SKIP_PREFIXES = ("WP_", "wpdb", "Walker", "Requests", "SimplePie", "PHPMailer", "Psr", "Symfony", "Composer")
SKIP_EXACT = {"self", "static", "parent", "Exception", "Throwable", "Error", "ArrayObject",
              "ArrayAccess", "Countable", "Iterator", "IteratorAggregate", "Traversable",
              "JsonSerializable", "Serializable", "Closure", "Generator", "stdClass", "DateTime",
              "DateTimeInterface", "DateTimeImmutable", "SoapClient", "SoapFault"}


def scan(plugin_dir: Path) -> tuple[set[str], set[str]]:
    defined: set[str] = set()
    referenced: set[str] = set()
    for path in plugin_dir.rglob("*.php"):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        defined.update(DEF_PATTERN.findall(text))
        for pattern in REF_PATTERNS:
            for name in pattern.findall(text):
                referenced.add(name.split("\\")[-1] if "\\" in name else name)
    return defined, referenced


def missing_classes(plugin_dir: Path) -> list[str]:
    defined, referenced = scan(plugin_dir)
    out = set()
    for name in referenced:
        if name in defined or name in SKIP_EXACT:
            continue
        if name.startswith(SKIP_PREFIXES):
            continue
        out.add(name)
    return sorted(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("plugin_dir")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    plugin_dir = Path(args.plugin_dir).resolve()
    names = missing_classes(plugin_dir) if plugin_dir.is_dir() else []

    lines = ["<?php", "", "// Generated by tools/bin/generate_missing_class_stubs.py -- do not edit.",
             f"// Plugin: {plugin_dir.name}", ""]
    for name in names:
        lines.append(f"class {name} {{}}")
    lines.append("")
    Path(args.output).write_text("\n".join(lines), encoding="utf-8")
    print(f"[stubs] {plugin_dir.name}: {len(names)} missing class(es) stubbed -> {args.output}")
    if names:
        print("[stubs] " + ", ".join(names[:12]) + (" ..." if len(names) > 12 else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
